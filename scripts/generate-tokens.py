import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
tokens = json.loads((root / 'packages/design-tokens/tokens.json').read_text())
css = ':root{--color-primary:' + tokens['color']['primary'] + ';--space-md:' + str(tokens['space']['md']) + 'px;--radius-card:' + str(tokens['radius']['card']) + 'px}\n'
(root / 'apps/web/public/tokens.css').write_text(css)
color = tokens['color']['primary'].lstrip('#')
(root / 'apps/pos/lib/design_system/tokens.dart').write_text("// Generated by scripts/generate-tokens.py; edit tokens.json.\nimport 'package:flutter/material.dart';\n\nabstract final class DesignTokens {\n  static const primary = Color(0xFF" + color + ");\n}\n")
